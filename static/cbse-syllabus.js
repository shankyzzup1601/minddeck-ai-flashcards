export function chaptersFor(classLevel, subject) {
  return CBSE_SYLLABUS[classLevel]?.[subject] || Object.freeze([]);
}

export function subjectGuide(subject) {
  return SUBJECT_REVISION_GUIDES[subject] || "Key definitions, concepts, applications and exam-ready recall points.";
}

export function syllabusChapterCount(classLevel, subjects = []) {
  return subjects.reduce((total, subject) => total + chaptersFor(classLevel, subject).length, 0);
}

export function totalSyllabusChapterCount() {
  return Object.values(CBSE_SYLLABUS).reduce(
    (classTotal, classCatalog) => classTotal + Object.values(classCatalog).reduce(
      (subjectTotal, chapters) => subjectTotal + chapters.length,
      0
    ),
    0
  );
}
